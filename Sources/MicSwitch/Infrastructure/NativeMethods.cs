    public static extern bool SetForegroundWindow(IntPtr hWnd);

    [DllImport("user32.dll")]
    public static extern uint GetDpiForWindow(IntPtr hWnd);

    /// <summary>The character a key types on the current layout (unshifted), or null if it types none.</summary>
    public static char? VirtualKeyToChar(int virtualKey)
    {
        const uint MAPVK_VK_TO_CHAR = 2;
        var result = MapVirtualKey((uint)virtualKey, MAPVK_VK_TO_CHAR) & 0x7FFF;
        return result is > 32 and < 0xFFFF ? (char)result : null;
    }
}
